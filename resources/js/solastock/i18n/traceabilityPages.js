export function traceabilityPageText(locale, key, params = {}, fallback) {
    const dictionary = locale === 'ar' ? traceabilityPagesAr : traceabilityPagesEn;
    const value = dictionary[key] ?? traceabilityPagesEn[key] ?? fallback ?? key;
    return String(value).replace(/:([A-Za-z0-9_]+)/g, (_, name) => params[name] ?? `:${name}`);
}

export function traceabilityStatusText(locale, value) {
    return traceabilityPageText(locale, `traceabilityPages.status.${value}`, {}, value);
}

export function traceabilityEventText(locale, value) {
    const key = {
        'Received / returned': 'traceabilityPages.event.receivedReturned',
        'Issued / shipped': 'traceabilityPages.event.issuedShipped',
    }[value];
    return key ? traceabilityPageText(locale, key) : value;
}

export function traceabilityRiskText(locale, count, days) {
    if (locale !== 'ar') {
        return traceabilityPageText(locale, 'traceabilityPages.hub.risk', {
            count,
            days,
            lots: traceabilityPageText(locale, count === 1 ? 'traceabilityPages.hub.lotSingular' : 'traceabilityPages.hub.lotPlural'),
            dayUnit: traceabilityPageText(locale, days === 1 ? 'traceabilityPages.hub.daySingular' : 'traceabilityPages.hub.dayPlural'),
        });
    }
    const category = new Intl.PluralRules('ar').select(Number(count));
    return traceabilityPageText(locale, `traceabilityPages.hub.risk.${category}`, { count, days });
}

export function traceabilityExpiredText(locale, count) {
    if (locale !== 'ar') {
        return traceabilityPageText(locale, 'traceabilityPages.hub.alreadyExpired', {
            count,
            lots: traceabilityPageText(locale, count === 1 ? 'traceabilityPages.hub.lotSingular' : 'traceabilityPages.hub.lotPlural'),
        });
    }
    const category = new Intl.PluralRules('ar').select(Number(count));
    return traceabilityPageText(locale, `traceabilityPages.hub.expired.${category}`, { count });
}
