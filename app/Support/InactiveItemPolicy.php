namespace App\Support;

use App\Models\Tenant\InternalConsumptionLine;
use App\Models\Tenant\InventoryAuditLog;
use App\Models\Tenant\Item;
use App\Models\Tenant\StockAdjustment;
use App\Models\Tenant\StockAdjustmentLine;
use App\Models\Tenant\SalesReturn;
use App\Models\Tenant\SalesReturnLine;
use App\Models\Tenant\StockCountLine;
use App\Models\Tenant\SupplierReturn;
use App\Models\Tenant\SupplierReturnLine;
use App\Services\Stock\StockMovement;
use App\Services\Stock\Support\Decimal;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Support\Facades\DB;
use Illuminate\Validation\ValidationException;

/**
 * Q12.3 / Q12.6 (owner decisions 2026-10-18): server-side inactive-item policy for SolaStock.
 *
 * Locking contract (shared with ItemDeactivationGuard and StockLedgerService::lockItems): every writer
 * that creates a stock document line / reservation for an item, or re-points a line to another item,
 * first takes SELECT ... FOR UPDATE on that item row inside the same transaction as the insert. A
 * deactivation takes the same lock before it checks for open documents, so the two serialize:
 *   - deactivation first  -> the writer waits, then reads is_active = 0 and is refused;
 *   - writer first        -> the deactivation waits, then sees the committed open line and is refused.
 * is_active is always read by the locking read itself (never a plain read that could come from an older
 * REPEATABLE READ snapshot).
 *
 * Inactive items:
 *   - refused: every new document line / reservation (adjustment increase, transfer, count, opening,
 *     goods receipt, shipment, internal consumption, supplier/sales return, purchase-order line, receiving
 *     request, pick list, reservation) and every ordinary ledger movement (StockLedgerService::post);
 *   - allowed (controlled corrective workflows):
 *       1. reversal of an existing posted document (StockLedgerService::reverse / applyExactReversal,
 *          incl. InventoryReversalService), which never passes through post(); and the internal-consumption
 *          return of a line of an already POSTED issue of the same item (the return document line is
 *          allowed here, its stock effect is applyExactReversal via returnIssuedQuantity);
 *       2. a stock-adjustment DECREASE (write-off / reduction) out of positive on-hand stock at that
 *          coordinate, never below zero even when negative stock is enabled, posted through the existing
 *          draft -> post workflow (perm:inventory.manage_adjustments on POST /adjustments/{id}/post); every such posting writes an
 *          inventory_audit_logs row "stock_adjustment.inactive_item_write_off". Mirrors Finance C7
 *          InactiveItemAdjustmentPolicy (NF-1198-03).
 *       3. (owner adjustment 2026-10-18) through their existing workflows/permissions, each posting audited as
 *          inventory_audit_logs "inactive_item.corrective_movement" (before.item_inactive = true, kind):
 *          (a) supplier return whose line references a POSTED, unreversed goods-receipt line of the item (the
 *              receipt also carries bill-originated receiving), reducing existing stock only, never below zero;
 *          (b) sales return whose line references a POSTED, unreversed shipment line of the item; may increase
 *              stock; cumulative returned quantity never above the shipped line quantity;
 *          (c) stock count lines and the count's own variance adjustment (StockCountService::post via
 *              duringCountPosting); decreases never below zero.
 *       Unlinked returns, receipts, transfers, shipments, PO lines, ordinary increasing adjustments stay refused.
 */
final class InactiveItemPolicy
{
    /** Lock the item row (same lock as a deactivation) and return its CURRENT active flag; null when absent. */
    public static function lockedIsActive(int $itemId): ?bool
    {
        $value = Item::query()->withoutGlobalScopes()->whereKey($itemId)->lockForUpdate()->value('is_active');

        return $value === null ? null : (bool) $value;
    }

    /** Called by GuardsInactiveItem inside the insert/update transaction of a document line or reservation. */
    public static function guardDocumentLine(Model $line): void
    {
        $itemId = (int) $line->getAttribute('item_id');
        if ($itemId <= 0) {
            return;
        }
        $active = self::lockedIsActive($itemId);
        if ($active !== false) {
            return; // active, or unknown item (the FK / document validation reports it)
        }
        if ($line instanceof StockAdjustmentLine && self::$countPosting > 0) {
            return; // (c) variance adjustment generated by StockCountService::post; the ledger re-checks
        }
        if ($line instanceof StockAdjustmentLine && $line->getAttribute('direction') === 'decrease') {
            self::assertWriteOffWithinStock($itemId, $line);

            return;
        }
        if ($line instanceof StockCountLine) {
            return; // (c) counting an inactive item is the controlled correction; posting is checked
        }
        if ($line instanceof SupplierReturnLine) {
            if (self::postedReceiptLine($line->getAttribute('goods_receipt_line_id'), $itemId) === null) {
                throw self::rejected($itemId); // (a) needs a posted receipt / bill-receipt source
            }
            self::assertWithinStock($itemId, (int) $line->getAttribute('warehouse_id'), (string) $line->getAttribute('quantity'), $line);

            return;
        }
        if ($line instanceof SalesReturnLine) {
            self::assertReturnWithinShipped($line, $itemId); // (b) needs a posted shipment line of this item

            return;
        }
        if ($line instanceof InternalConsumptionLine && self::returnsPostedIssueLine($line, $itemId)) {
            return; // partial reversal (return) of an already posted issue of this item
        }
        throw self::rejected($itemId);
    }

    /**
     * Called by StockLedgerService::applyMovement (ordinary post, never a reversal) after the item and
     * balance rows are locked. $onHand is the locked balance at the movement's coordinate.
     */
    public static function assertLedgerMovementAllowed(StockMovement $m, string $onHand, string $qty, int $orgId): void
    {
        if (self::lockedIsActive($m->itemId) !== false) {
            return;
        }
        $kind = match (true) {
            $m->sourceType === StockAdjustment::class && self::$countPosting > 0 => 'stock_count',
            $m->sourceType === StockAdjustment::class && $m->direction === 'out' => 'write_off',
            $m->sourceType === SupplierReturn::class && $m->direction === 'out' => 'supplier_return',
            $m->sourceType === SalesReturn::class && $m->direction === 'in' => 'sales_return',
            default => null,
        };
        if ($kind === null) {
            throw self::rejected($m->itemId);
        }
        if ($m->direction === 'out' && (! Decimal::gt($onHand, '0') || Decimal::lt(Decimal::sub($onHand, $qty), '0'))) {
            throw self::writeOffExceeds($m->itemId); // reductions only out of existing stock, never below zero
        }
        if ($kind === 'supplier_return') {
            $grnLine = DB::connection('tenant')->table('supplier_return_lines')->where('id', $m->sourceLineId)->where('supplier_return_id', $m->sourceId)->value('goods_receipt_line_id');
            if (self::postedReceiptLine($grnLine, $m->itemId) === null) {
                throw self::rejected($m->itemId);
            }
        }
        if ($kind === 'sales_return') {
            $line = SalesReturnLine::query()->withoutGlobalScopes()->whereKey($m->sourceLineId)->where('sales_return_id', $m->sourceId)->first();
            if (! $line) {
                throw self::rejected($m->itemId);
            }
            self::assertReturnWithinShipped($line, $m->itemId, true);
        }
        InventoryAuditLog::create([
            'organization_id' => $orgId,
            'actor_user_id' => auth()->id(),
            'action' => $kind === 'write_off' ? 'stock_adjustment.inactive_item_write_off' : 'inactive_item.corrective_movement',
            'entity_type' => match ($kind) { 'supplier_return' => 'supplier_return', 'sales_return' => 'sales_return', default => 'stock_adjustment' },
            'entity_id' => $m->sourceId,
            'before' => ['item_id' => $m->itemId, 'item_inactive' => true, 'kind' => $kind, 'warehouse_id' => $m->warehouseId, 'on_hand_qty' => Decimal::qty($onHand)],
            'after' => ['on_hand_qty' => Decimal::qty($m->direction === 'out' ? Decimal::sub($onHand, $qty) : Decimal::add($onHand, $qty)),
                'direction' => $m->direction, 'quantity' => Decimal::qty($qty), 'source_line_id' => $m->sourceLineId]
                + ($kind === 'write_off' ? ['written_off_qty' => Decimal::qty($qty)] : []),
            'document_ref' => $kind.':'.$m->sourceId,
            'created_at' => now(),
        ]);
    }

    /** (c) Marks the variance adjustment that StockCountService::post creates and posts. */
    public static function duringCountPosting(callable $callback): mixed
    {
        self::$countPosting++;
        try {
            return $callback();
        } finally {
            self::$countPosting--;
        }
    }

    private static int $countPosting = 0;

    private static function postedReceiptLine(mixed $grnLineId, int $itemId): ?int
    {
        if ($grnLineId === null) {
            return null;
        }
        $id = DB::connection('tenant')->table('goods_receipt_lines as l')->join('goods_receipts as h', 'h.id', '=', 'l.goods_receipt_id')
            ->where('l.id', $grnLineId)->where('l.item_id', $itemId)->where('h.status', 'posted')
            ->when(DB::connection('tenant')->getSchemaBuilder()->hasColumn('goods_receipts', 'reversed_at'), fn ($q) => $q->whereNull('h.reversed_at'))
            ->value('l.id');

        return $id === null ? null : (int) $id;
    }

    /** (b) the line must return a posted, unreversed shipment line of this item, cumulatively within its quantity. */
    private static function assertReturnWithinShipped(SalesReturnLine $line, int $itemId, bool $postedOnly = false): void
    {
        $db = DB::connection('tenant');
        $source = $db->table('shipment_lines as l')->join('shipments as h', 'h.id', '=', 'l.shipment_id')
            ->where('l.id', $line->getAttribute('source_shipment_line_id'))->where('l.item_id', $itemId)->where('h.status', 'posted')
            ->when($db->getSchemaBuilder()->hasColumn('shipments', 'reversed_at'), fn ($q) => $q->whereNull('h.reversed_at'))
            ->sharedLock()->first(['l.id', 'l.quantity']);
        if ($line->getAttribute('source_shipment_line_id') === null || ! $source) {
            throw self::rejected($itemId);
        }
        $already = (string) $db->table('sales_return_lines as l')->join('sales_returns as r', 'r.id', '=', 'l.sales_return_id')
            ->where('l.source_shipment_line_id', $source->id)->whereNull('r.deleted_at')
            ->when($line->exists, fn ($q) => $q->where('l.id', '!=', $line->getKey()))
            ->when($postedOnly, fn ($q) => $q->where('r.status', 'posted'), fn ($q) => $q->where('r.status', '!=', 'cancelled'))
            ->sum('l.returned_qty');
        if (Decimal::gt(Decimal::add($already, (string) $line->getAttribute('returned_qty')), (string) $source->quantity)) {
            throw self::returnExceedsShipped($itemId);
        }
    }

    private static function assertWithinStock(int $itemId, int $warehouseId, string $qty, Model $line): void
    {
        $query = DB::connection('tenant')->table('stock_balances')->where('item_id', $itemId)->where('warehouse_id', $warehouseId);
        foreach (['variant_id', 'lot_id', 'bin_id'] as $column) {
            if ($line->getAttribute($column) !== null) {
                $query->where($column, $line->getAttribute($column));
            }
        }
        $onHand = (string) ($query->sharedLock()->sum('on_hand_qty') ?? '0');
        if (! Decimal::gt($onHand, '0') || Decimal::lt(Decimal::sub($onHand, $qty), '0')) {
            throw self::writeOffExceeds($itemId);
        }
    }

    private static function returnExceedsShipped(int $itemId): ValidationException
    {
        return ValidationException::withMessages([
            'item_id' => [__('inventory.catalog.inactive_return_exceeds_shipped')],
            'inactive_item_ids' => [$itemId],
        ]);
    }

    /**
     * Unit normalisation of a document line (UnitConversionResolver) for an inactive item: refuse with the
     * inactive-item error, except a stock-adjustment decrease line, which the locked line guard and the
     * ledger re-check against positive stock.
     */
    public static function assertConversionAllowed(Item $item, array $line): void
    {
        // decrease = write-off; source_line_id = sales return of a shipment line (re-checked by the line guard)
        if (($line['direction'] ?? null) !== 'decrease' && empty($line['source_line_id']) && self::$countPosting === 0) {
            throw self::rejected((int) $item->id);
        }
    }

    private static function returnsPostedIssueLine(InternalConsumptionLine $line, int $itemId): bool
    {
        $original = $line->getAttribute('original_line_id');
        if ($original === null) {
            return false;
        }

        return DB::connection('tenant')->table('internal_consumption_lines as l')
            ->join('internal_consumptions as h', 'h.id', '=', 'l.internal_consumption_id')
            ->where('l.id', $original)->where('l.item_id', $itemId)
            ->where('h.kind', 'issue')->where('h.status', 'posted')->exists();
    }

    private static function assertWriteOffWithinStock(int $itemId, StockAdjustmentLine $line): void
    {
        $warehouseId = StockAdjustment::query()->withoutGlobalScopes()->whereKey($line->getAttribute('stock_adjustment_id'))->value('warehouse_id');
        $query = DB::connection('tenant')->table('stock_balances')->where('item_id', $itemId)->where('warehouse_id', $warehouseId);
        foreach (['variant_id', 'lot_id', 'bin_id'] as $column) {
            if ($line->getAttribute($column) !== null) {
                $query->where($column, $line->getAttribute($column));
            }
        }
        $onHand = (string) ($query->sharedLock()->sum('on_hand_qty') ?? '0');
        $qty = (string) $line->getAttribute('quantity');
        if (! Decimal::gt($onHand, '0') || Decimal::lt(Decimal::sub($onHand, $qty), '0')) {
            throw self::writeOffExceeds($itemId);
        }
    }

    private static function rejected(int $itemId): ValidationException
    {
        return ValidationException::withMessages([
            'item_id' => [__('inventory.catalog.inactive_item_rejected')],
            'inactive_item_ids' => [$itemId],
        ]);
    }

    private static function writeOffExceeds(int $itemId): ValidationException
    {
        return ValidationException::withMessages([
            'item_id' => [__('inventory.catalog.inactive_write_off_exceeds_stock')],
            'inactive_item_ids' => [$itemId],
        ]);
    }
}
